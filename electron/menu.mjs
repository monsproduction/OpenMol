let lang = 'de'
export function setMenuLang(l) {
  lang = l === 'en' ? 'en' : 'de'
}
export const menuLang = () => lang

/** @param {() => Electron.BrowserWindow | null} getWin */
export function buildMenu(getWin, actions = {}) {
  const t = L[lang]
  const mac = process.platform === 'darwin'
  const send = (cmd) => () => getWin()?.webContents.send('openmol:menu', cmd)
  const item = (label, cmd, accelerator) => ({ label, accelerator, click: send(cmd) })

  /** @type {Electron.MenuItemConstructorOptions[]} */
  const tpl = [
    ...(mac
      ? [
          {
            label: app.name,
            submenu: [
              { role: 'about', label: t.about },
              { label: t.updates, click: () => actions.checkUpdates?.() },
              { type: 'separator' },
              item(t.settings, 'settings', 'CmdOrCtrl+,'),
              { type: 'separator' },
              { role: 'services' },
              { type: 'separator' },
              { role: 'hide' },
              { role: 'hideOthers' },
              { role: 'unhide' },
              { type: 'separator' },
              { role: 'quit' },
            ],
          },
        ]
      : []),
    {
      label: mac ? t.file : t.fileWin,
      submenu: [
        item(t.new, 'new', 'CmdOrCtrl+N'),
        item(t.newTab, 'newTab', 'CmdOrCtrl+T'),
        item(t.open, 'open', 'CmdOrCtrl+O'),
        ...(mac ? [{ role: 'recentDocuments', label: t.recent, submenu: [{ role: 'clearRecentDocuments', label: t.clearRecent }] }] : []),
        { type: 'separator' },
        item(t.closeTab, 'closeTab', 'CmdOrCtrl+W'),
        { role: 'close', label: t.close, accelerator: 'CmdOrCtrl+Shift+W' },
        item(t.save, 'save', 'CmdOrCtrl+S'),
        item(t.saveAs, 'saveAs', 'CmdOrCtrl+Shift+S'),
        { type: 'separator' },
        item(t.import, 'import'),
        {
          label: t.export,
          submenu: [item(t.exportDialog, 'exportDialog', 'CmdOrCtrl+E'), { type: 'separator' }, item(t.pdf, 'exportPdf'), item(t.png, 'exportPng'), item(t.svg, 'exportSvg'), item(t.mol, 'exportMol'), item(t.cdxml, 'exportCdxml')],
        },
        // Word-Add-in: Mac und Windows (unter Linux gibt es kein Word)
        ...(mac || process.platform === 'win32' ? [{ type: 'separator' }, { label: t.wordAddin, click: () => actions.wordAddin?.() }] : []),
        ...(mac ? [] : [{ type: 'separator' }, item(t.settings, 'settings', 'CmdOrCtrl+,'), { role: 'quit' }]),
      ],
    },
    {
      label: t.edit,
      submenu: [
        item(t.undo, 'undo', 'CmdOrCtrl+Z'),
        item(t.redo, 'redo', 'CmdOrCtrl+Shift+Z'),
        { type: 'separator' },
        item(t.cut, 'cut', 'CmdOrCtrl+X'),
        item(t.copy, 'copy', 'CmdOrCtrl+C'),
        item(t.copyImage, 'copyImage'),
        item(t.paste, 'paste', 'CmdOrCtrl+V'),
        item(t.duplicate, 'duplicate', 'CmdOrCtrl+D'),
        item(t.delete, 'delete'),
        { type: 'separator' },
        item(t.selectAll, 'selectAll', 'CmdOrCtrl+A'),
      ],
    },
    {
      label: t.structure,
      submenu: [
        item(t.cleanStructure, 'cleanStructure', 'CmdOrCtrl+Shift+K'),
        item(t.cleanReaction, 'cleanReaction', 'CmdOrCtrl+Shift+X'),
        item(t.toggle3d, 'toggle3d', 'CmdOrCtrl+Shift+D'),
        { type: 'separator' },
        item(t.stoichTable, 'stoichTable'),
        { type: 'separator' },
        item(t.contract, 'contract'),
        item(t.expand, 'expand'),
        { type: 'separator' },
        item(t.nameToStructure, 'nameToStructure'),
        item(t.structureToName, 'structureToName'),
        {
          label: t.analysis,
          submenu: [item(t.formula, 'anFormula'), item(t.mw, 'anMw'), item(t.exact, 'anExact'), { type: 'separator' }, item(t.all4, 'anAll')],
        },
      ],
    },
    {
      label: t.view,
      submenu: [
        item(t.fit, 'fit', 'CmdOrCtrl+0'),
        item(t.zoomIn, 'zoomIn', 'CmdOrCtrl+Plus'),
        item(t.zoomOut, 'zoomOut', 'CmdOrCtrl+-'),
        item(t.zoom100, 'zoom100'),
        { type: 'separator' },
        item(t.inspector, 'inspector', 'CmdOrCtrl+\\'),
        item(t.theme, 'theme'),
        { type: 'separator' },
        item(t.nextTab, 'nextTab', 'Ctrl+Tab'),
        item(t.prevTab, 'prevTab', 'Ctrl+Shift+Tab'),
        { type: 'separator' },
        { role: 'togglefullscreen', label: t.fullscreen },
      ],
    },
    { role: 'windowMenu', label: t.window },
    {
      role: 'help',
      label: t.help,
      submenu: [
        item(t.shortcuts, 'help'),
        item(t.settingsDir, 'settingsDir'),
        ...(mac ? [] : [{ type: 'separator' }, { label: t.updates, click: () => actions.checkUpdates?.() }, { role: 'about', label: t.about }]),
      ],
    },
  ]
  return Menu.buildFromTemplate(tpl)
}
